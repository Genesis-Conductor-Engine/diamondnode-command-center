def derive_description(text: str, fallback: str) -> str:
    """First readable sentence-ish run of body text, capped for a meta description."""
    text = re.sub(r"\s+", " ", text).strip()
    if len(text) < 40:
        return fallback
    cut = text[:300]
    for stop in (". ", " · ", " — ", " • "):
        if stop in cut[60:]:
            cut = cut[: 60 + cut[60:].index(stop)]
            break
    return (cut[:157] + "…") if len(cut) > 158 else cut


def visible_text(src: str) -> str:
    s = re.sub(r"<script.*?</script>", " ", src, flags=re.S | re.I)
    s = re.sub(r"<style.*?</style>", " ", s, flags=re.S | re.I)
    return html.unescape(re.sub(r"<[^>]+>", " ", s))


def page_title(src: str, default: str) -> str:
    m = re.search(r"<title>(.*?)</title>", src, flags=re.S | re.I)
    return html.unescape(m.group(1)).strip() if m else default


def jsonld(*blocks: dict) -> str:
    # @context is not optional. Without it the payload is untyped JSON and every
    # consumer — Google rich results, answer engines — silently ignores it, which
    # looks identical to "we shipped structured data" right up until nothing indexes.
    payload: dict = {"@context": "https://schema.org"}
    if len(blocks) == 1:
        payload.update(blocks[0])
    else:
        payload["@graph"] = list(blocks)
    body = json.dumps(payload, indent=2, ensure_ascii=False)
    return f'<script type="application/ld+json">\n{body}\n</script>'


