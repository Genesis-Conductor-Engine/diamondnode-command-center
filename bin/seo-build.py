def main() -> int:
    global SITE
    ap = argparse.ArgumentParser()
    ap.add_argument("--root", type=Path, default=ROOT)
    ap.add_argument("--site", default=SITE)
    ap.add_argument("--check", action="store_true",
                    help="report what would change; write nothing; exit 1 if stale")
    args = ap.parse_args()

    SITE = args.site.rstrip("/")
    root: Path = args.root
    if not root.is_dir():
        print(f"fatal: {root} is not a directory", file=sys.stderr)
        return 2

    html_files = sorted(p for p in root.glob("*.html"))
    if not html_files:
        print(f"fatal: no .html under {root}", file=sys.stderr)
        return 2

    sitemap_rows: list[tuple[str, bool]] = []
    llms_rows: list[tuple[str, str, str]] = []
    changed: list[str] = []

    for path in html_files:
        slug = path.name
        is_index = slug == "index.html"
        src = path.read_text(encoding="utf-8", errors="replace")
        meta = PAGES.get(slug, {})
        title = meta.get("title") or page_title(src, slug)
        desc = meta.get("desc") or derive_description(
            visible_text(src), f"{title} — a Genesis Conductor exhibit surface.")
        kind = meta.get("type", "WebPage")

        block = head_block(slug, title, desc, kind, is_index)
        if args.check:
            if BEGIN not in src or block not in src:
                changed.append(slug)
        elif inject(path, block):
            changed.append(slug)

        if slug not in NOINDEX:
            sitemap_rows.append((slug, is_index))
            llms_rows.append((slug, title, desc))

    artifacts = {
        "robots.txt": build_robots(),
        "sitemap.xml": build_sitemap(sitemap_rows),
        "llms.txt": build_llms(llms_rows),
        "_headers": build_headers(),
        "manifest.json": build_manifest(),
    }
    for name, content in artifacts.items():
        target = root / name
        if args.check:
            if not target.exists() or target.read_text(encoding="utf-8") != content:
                changed.append(name)
        elif not target.exists() or target.read_text(encoding="utf-8") != content:
            target.write_text(content, encoding="utf-8")
            changed.append(name)

    if not args.check and not (root / "og-image.png").exists():
        made = build_og_image(root)
        changed += made
        if not made:
            print("warn: Pillow unavailable — og:image tags point at a missing file",
                  file=sys.stderr)
    elif args.check and not (root / "og-image.png").exists():
        changed.append("og-image.png")

    verb = "would change" if args.check else "wrote"
    print(f"{verb}: {len(changed)} file(s)")
    for c in changed:
        print(f"  {c}")
    print(f"pages indexed: {len(html_files)}  root: {root}  site: {SITE}")
    return 1 if (args.check and changed) else 0


if __name__ == "__main__":
    raise SystemExit(main())
