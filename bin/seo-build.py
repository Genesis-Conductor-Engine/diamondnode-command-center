#!/usr/bin/env python3
"""seo-build — generate the discovery surface for the yennefer.quest deploy tree.

The site shipped with charset + viewport + <title> and nothing else: no description,
no canonical, no Open Graph, no structured data, no robots.txt, no sitemap. Search
engines had nothing to rank, social unfurls were bare, and answer/generative engines
had no machine-readable statement of what any page is.

Three audiences, three different artifacts — they are not the same job:

  SEO  (search)      crawlable metadata: description, canonical, robots directives,
                     sitemap.xml, cache/security headers.
  AEO  (answers)     schema.org JSON-LD so an answer engine can extract entities and
                     answer directly — WebSite, Organization, per-page WebPage, and a
                     FAQPage whose questions are the ones a person actually asks.
  GEO  (generative)  llms.txt / llms-full.txt plus an explicit AI-crawler policy, so a
                     model grounding an answer reads a curated summary instead of
                     scraping a JS-rendered canvas app and hallucinating the rest.

Idempotent: each page gets one <!-- SEO:BEGIN --> … <!-- SEO:END --> block, replaced
wholesale on re-run. Safe to run in CI or by hand after editing any page.

Usage:
    seo-build.py [--root DIR] [--site URL] [--check]

--check exits non-zero if anything would change, without writing (for CI).
"""

