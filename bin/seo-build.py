def build_og_image(root: Path) -> list[str]:
    """Render the social card and app icons.

    A summary_large_image card with no image is worse than no card tag at all — X and
    Facebook fall back to a bare grey box on every share. The site had exactly one
    image, a user art upload sitting inside a Disallow: path, so the card art is
    generated here instead: same warm palette as the site (--warm-bg/--ember/--gold/
    --soft), composed as concentric orthogonal apertures so it reads as a hearth
    rather than as a logo nobody has.
    """
    try:
        from PIL import Image, ImageDraw, ImageFont, ImageFilter
    except ImportError:
        return []

    BG, EMBER, GOLD, SOFT = (26, 20, 15), (230, 126, 34), (212, 175, 55), (232, 213, 183)
    W, H = 1200, 630

    def font(bold: bool, size: int):
        for path in (
            "/usr/share/fonts/truetype/lato/Lato-{}.ttf".format("Bold" if bold else "Regular"),
            "/usr/share/fonts/truetype/dejavu/DejaVuSans{}.ttf".format("-Bold" if bold else ""),
        ):
            if Path(path).exists():
                try:
                    return ImageFont.truetype(path, size)
                except OSError:
                    pass
        return ImageFont.load_default()

    img = Image.new("RGB", (W, H), BG)

    # Ember glow: drawn small and upscaled, which is both fast and gives the soft
    # falloff a per-pixel loop at full size would take seconds to produce.
    g = Image.new("L", (60, 32), 0)
    gd = ImageDraw.Draw(g)
    for i in range(14, 0, -1):
        gd.ellipse([30 - i * 2.0, 16 - i * 1.1, 30 + i * 2.0, 16 + i * 1.1],
                   fill=int(120 * (1 - i / 14) ** 2))
    glow = g.resize((W, H), Image.BICUBIC).filter(ImageFilter.GaussianBlur(40))
    img = Image.composite(Image.new("RGB", (W, H), EMBER), img, glow.point(lambda v: v // 3))

    d = ImageDraw.Draw(img)

    # Concentric orthogonal apertures — the square-on-square symmetry is the point.
    cx, cy = W // 2, H // 2
    for i, (half_w, half_h, col, wdt) in enumerate([
        (430, 232, GOLD, 2), (386, 205, EMBER, 1), (342, 178, GOLD, 1),
    ]):
        shade = tuple(int(c * (0.85 - 0.18 * i)) for c in col)
        d.rectangle([cx - half_w, cy - half_h, cx + half_w, cy + half_h],
                    outline=shade, width=wdt)

    # Corner ticks: break the frame so it reads as an aperture, not a border.
    for sx in (-1, 1):
        for sy in (-1, 1):
            x, y = cx + sx * 430, cy + sy * 232
            d.line([x, y, x - sx * 54, y], fill=BG, width=5)
            d.line([x, y, x, y - sy * 40], fill=BG, width=5)
            d.line([x - sx * 16, y - sy * 16, x - sx * 40, y - sy * 16], fill=EMBER, width=3)
            d.line([x - sx * 16, y - sy * 16, x - sx * 16, y - sy * 34], fill=EMBER, width=3)

    def centered(text, fnt, y, fill, spacing=0):
        if spacing:
            widths = [d.textlength(ch, font=fnt) for ch in text]
            total = sum(widths) + spacing * (len(text) - 1)
            x = (W - total) / 2
            for ch, w in zip(text, widths):
                d.text((x, y), ch, font=fnt, fill=fill)
                x += w + spacing
        else:
            d.text(((W - d.textlength(text, font=fnt)) / 2, y), text, font=fnt, fill=fill)

    centered("THE HEARTH", font(True, 92), cy - 118, GOLD, spacing=10)
    centered("AGENT TWINS LIVE STUDIO", font(False, 30), cy + 2, SOFT, spacing=7)
    d.line([cx - 150, cy + 62, cx + 150, cy + 62], fill=EMBER, width=2)
    centered("Fable 5  ·  live agent state  ·  QFLOP telemetry", font(False, 23),
             cy + 92, tuple(int(c * 0.72) for c in SOFT))

    small = font(False, 21)
    d.text((72, H - 62), ORG["name"].upper(), font=small, fill=EMBER)
    d.text((W - 72 - d.textlength("yennefer.quest", font=small), H - 62),
           "yennefer.quest", font=small, fill=tuple(int(c * 0.6) for c in SOFT))

    written = []
    og = root / "og-image.png"
    img.save(og, "PNG", optimize=True)
    written.append(og.name)

    # Square icons for the manifest and favicon, cropped from the same composition.
    sq = img.crop((cx - 315, cy - 315, cx + 315, cy + 315))
    for name, size in (("icon-512.png", 512), ("icon-192.png", 192), ("favicon.png", 48)):
        sq.resize((size, size), Image.LANCZOS).save(root / name, "PNG", optimize=True)
        written.append(name)
    return written


